use std::path::PathBuf;
use std::process::ExitCode;

use clap::{Args, Parser, Subcommand};
use world::FileWorld;

const SOURCE_HELP: &str = "\
Parses the entry file with the Typst syntax parser and walks the syntax tree.
Nothing is evaluated or compiled. Markup is reported wherever it is written,
whether or not the surrounding code would run: unused variables, function
bodies, unexecuted branches, show rules and content passed to functions.

Included:
  - Authored text in markup. Escapes are decoded (\\# gives #) and shorthands
    give their characters (-- gives an en dash, ... gives an ellipsis). ~ gives
    a space, because all whitespace is collapsed. Smart quotes are kept as typed.
  - Markup inside code: content blocks [...] at any depth, including arguments,
    let and set bodies, show replacements, function bodies and both branches of
    a conditional.
  - Imports and includes whose path is a plain string literal. The path is
    resolved relative to the importing file (a leading / means the entry file's
    directory). Target files are parsed, never executed, and their markup is
    handled as above. Other paths (variables, packages, escapes) are reported
    on stderr as warnings and not followed.

Excluded:
  - String literals, including strings passed to functions and displayed strings.
  - Identifiers, function names, labels, numbers, operators, keywords and paths.
  - Comments, raw text and code blocks, and math equations.
  - Links and reference markers (@label). Markup in a reference supplement
    (@label[...]) is included. Heading numbers and any other text generated by
    numbering, counters, show rules or other evaluation are not written in the
    source and are not included.

Units and boundaries:
  - Output is a sequence of units. Each unit is printed on its own paragraph.
  - Paragraph breaks, headings, list items, enum items and term items each end
    the current unit.
  - A content block that is a non-trailing argument, or a content block in code
    that is not a trailing argument, is its own unit. Trailing content blocks
    f(..)[body] and bare [body] stay inline with the surrounding text.
  - Any other embedded element (code expression, math, raw text, link, reference)
    ends the unit. Prose on either side is emitted as separate units, so no
    words are removed and joined into a sentence that was not written.
  - Whitespace is collapsed. Explicit line breaks become newlines inside a unit.
    Soft hyphens are removed.

Diagnostics go to stderr. Syntax errors and unreadable followed files stop the
run with exit status 1 and no prose. Use --trace to see each decision.";

const COMPILED_HELP: &str = "\
Compiles the entry file with Typst 0.15.1 and extracts text from the resulting
PagedDocument by reading semantic tags and text runs. Nothing is read from the
source text itself.

Included:
  - Text rendered in the document body: paragraphs (including paragraphs that
    span pages), headings, captions, table cells, list and enum items, quotation
    text, and footnote bodies.
  - Text produced by evaluation and rendered: function results, show rule
    replacements, references, and generated numbering or prefixes.

Excluded:
  - Page headers and footers, and in-text footnote reference markers.
  - Image alternative text, which is not body prose.
  - Text that is not rendered, such as unused variables, unexecuted branches and
    unused functions.

Known limitations (not fixed here): block and quote bodies without paragraph
boundaries, enum items that run together, bullet and number markers, lost
spaces from layout gaps, explicit line breaks joined by spaces, and non-prose
rendered text (raw blocks, inline raw, and math rendered as Unicode glyphs)
included as text.

Units are printed as paragraphs. Untagged text is reported on stderr. Compile
errors go to stderr with exit status 1.";

#[derive(Parser)]
#[command(
    name = "typst-prose",
    about = "Extract prose from a Typst document",
    subcommand_required = true,
    arg_required_else_help = true
)]
struct Cli {
    #[command(subcommand)]
    mode: Mode,
}

#[derive(Subcommand)]
enum Mode {
    /// Extract prose by walking the Typst syntax tree, without evaluation
    #[command(long_about = SOURCE_HELP)]
    Source(Input),
    /// Extract prose from the compiled document
    #[command(long_about = COMPILED_HELP)]
    Compiled(Input),
}

#[derive(Args)]
struct Input {
    /// Entry .typ file
    input: PathBuf,
    /// Print a diagnostic trace to stdout instead of prose
    #[arg(long)]
    trace: bool,
}

fn main() -> ExitCode {
    match Cli::parse().mode {
        Mode::Source(input) => run_source(&input),
        Mode::Compiled(input) => run_compiled(&input),
    }
}

fn run_source(input: &Input) -> ExitCode {
    match source::extract(&input.input, input.trace) {
        Ok(extraction) => {
            for warning in &extraction.warnings {
                eprintln!("{warning}");
            }
            if input.trace {
                print!("{}", extraction.trace);
            } else {
                print!("{}", output::render(&extraction.units));
            }
            ExitCode::SUCCESS
        }
        Err(errors) => {
            for error in errors {
                eprintln!("{error}");
            }
            ExitCode::from(1)
        }
    }
}

fn run_compiled(input: &Input) -> ExitCode {
    let world = match FileWorld::new(&input.input) {
        Ok(world) => world,
        Err(e) => {
            eprintln!("error: {e}");
            return ExitCode::from(1);
        }
    };
    let doc = match world.compile() {
        Ok(doc) => doc,
        Err(errors) => {
            for e in errors {
                eprintln!("error: {}", e.message);
            }
            return ExitCode::from(1);
        }
    };

    if input.trace {
        let mut tracer = trace::Tracer::new(&world);
        tracer.document(&doc);
        print!("{}", tracer.out);
        return ExitCode::SUCCESS;
    }

    let extraction = extract::extract(&doc);
    for text in &extraction.untagged {
        eprintln!("untagged text: {text:?}");
    }
    if extraction.dropped_artifacts > 0 {
        eprintln!("suppressed text runs (artifact or footnote reference): {}", extraction.dropped_artifacts);
    }
    if extraction.unmatched_tags > 0 {
        eprintln!("unmatched tags: {}", extraction.unmatched_tags);
    }
    print!("{}", extraction.text());
    ExitCode::SUCCESS
}
