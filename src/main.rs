#[derive(Parser)]
#[command(
    name = "typst-prose",
    about = "Extract prose from a Typst document",
    subcommand_required = true,
    arg_required_else_help = true
)]
struct Cli {
    #[command(subcommand)]
    mode: Mode,
}

#[derive(Subcommand)]
enum Mode {
    /// Extract prose by walking the Typst syntax tree, without evaluation
    #[command(long_about = SOURCE_HELP)]
    Source(SourceArgs),
    /// Extract prose from the compiled document
    #[command(long_about = COMPILED_HELP)]
    Compiled(CompiledArgs),
}

#[derive(Args)]
struct Input {
    /// Entry .typ file
    input: PathBuf,
    /// Project root for absolute and escaping paths. Defaults to the entry file's directory.
    #[arg(long, env = "TYPST_ROOT", value_name = "DIR")]
    root: Option<PathBuf>,
    /// Print a diagnostic trace to stdout instead of prose
    #[arg(long)]
    trace: bool,
}

#[derive(Args)]
struct CompiledArgs {
    #[command(flatten)]
    input: Input,
    /// Date that datetime.today() returns, as YYYY-MM-DD. Empty or missing uses the system date.
    #[arg(long, value_name = "YYYY-MM-DD")]
    date: Option<String>,
    /// Directory searched recursively for fonts. Repeatable. Searched before the system fonts.
    #[arg(long = "font-path", value_name = "DIR")]
    font_paths: Vec<PathBuf>,
    /// Use only the fonts embedded in the tool, so the output does not depend on the machine.
    #[arg(long)]
    no_system_fonts: bool,
}

/// The fonts a document is laid out with, in search order: the font paths, the system fonts,
/// then the fonts embedded in the tool. Typst takes the first face that matches a family.
fn build_fonts(args: &CompiledArgs) -> FontStore {
    let mut fonts = FontStore::new();
    for dir in &args.font_paths {
        fonts.extend(typst_kit::fonts::scan(dir));
    }
    if !args.no_system_fonts {
        fonts.extend(typst_kit::fonts::system());
    }
    fonts.extend(typst_kit::fonts::embedded());
    fonts
}

#[derive(Args)]
struct SourceArgs {
    #[command(flatten)]
    input: Input,
    /// Text written in place of an inline element that renders no authored text. Empty removes it.
    #[arg(long, value_name = "TEXT", default_value = "[...]")]
    placeholder_text: String,
}

fn main() -> ExitCode {
    match Cli::parse().mode {
        Mode::Source(args) => run_source(&args),
        Mode::Compiled(args) => run_compiled(&args),
    }
}

fn locate(input: &Input) -> Result<Project, ExitCode> {
    Project::locate(&input.input, input.root.as_deref()).map_err(|e| {
        eprintln!("{e}");
        ExitCode::from(1)
    })
}

fn run_source(args: &SourceArgs) -> ExitCode {
    let input = &args.input;
    let project = match locate(input) {
        Ok(project) => project,
        Err(code) => return code,
    };
    match source::extract(&project, input.trace, &args.placeholder_text) {
        Ok(extraction) => {
            for warning in &extraction.warnings {
                eprintln!("{warning}");
            }
            if input.trace {
                print!("{}", extraction.trace);
            } else {
                print!("{}", output::render(&extraction.units));
            }
            ExitCode::SUCCESS
        }
        Err(errors) => {
            for error in errors {
                eprintln!("{error}");
            }
            ExitCode::from(1)
        }
    }
}

/// The clock behind `datetime.today()`: the system clock, or the fixed `--date`.
fn build_time(date: Option<&str>) -> Result<Time, String> {
    let Some(text) = date.filter(|text| !text.is_empty()) else {
        return Ok(Time::system());
    };
    let invalid = || format!("error: invalid --date `{text}`: expected YYYY-MM-DD");
    // chrono accepts unpadded fields, so the length check is what enforces YYYY-MM-DD.
    if text.len() != 10 {
        return Err(invalid());
    }
    let parsed = NaiveDate::parse_from_str(text, "%Y-%m-%d").map_err(|_| invalid())?;
    let day = Datetime::from_ymd(parsed.year(), parsed.month() as u8, parsed.day() as u8).ok_or_else(invalid)?;
    Time::fixed(day).map_err(|e| format!("error: --date `{text}`: {e}"))
}

fn run_compiled(args: &CompiledArgs) -> ExitCode {
    let input = &args.input;
    let project = match locate(input) {
        Ok(project) => project,
        Err(code) => return code,
    };
    let time = match build_time(args.date.as_deref()) {
        Ok(time) => time,
        Err(message) => {
            eprintln!("{message}");
            return ExitCode::from(1);
        }
    };
    let world = FileWorld::new(&project, time, build_fonts(args));
    let doc = match world.compile() {
        Ok(doc) => doc,
        Err(errors) => {
            for e in errors {
                eprintln!("error: {}", e.message);
            }
            return ExitCode::from(1);
        }
    };

    if input.trace {
        let mut tracer = trace::Tracer::new(&world);
        tracer.document(&doc);
        print!("{}", tracer.out);
        return ExitCode::SUCCESS;
    }

    let extraction = extract::extract(&doc);
    for text in &extraction.untagged {
        eprintln!("untagged text: {text:?}");
    }
    if extraction.dropped_artifacts > 0 {
        eprintln!("suppressed text runs (artifact or footnote reference): {}", extraction.dropped_artifacts);
    }
    if extraction.clipped_runs > 0 {
        eprintln!("text runs outside a clip box: {}", extraction.clipped_runs);
    }
    if extraction.repeated_runs > 0 {
        eprintln!("text runs in repeated table cells: {}", extraction.repeated_runs);
    }
    if extraction.unmatched_tags > 0 {
        eprintln!("unmatched tags: {}", extraction.unmatched_tags);
    }
    print!("{}", extraction.text());
    ExitCode::SUCCESS
}
